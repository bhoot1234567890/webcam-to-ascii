"""Explicit, offline-after-generation canonical PNG fixture creation.

Run from the repository root with .venv-qa/bin/python -m qa.make_fixtures.
Only this command may ask scikit-image to obtain its sample image data.
"""
from __future__ import annotations

import argparse
from io import BytesIO
import json
from pathlib import Path

import numpy as np
from PIL import Image
from skimage import data

from qa.fixture_io import load_manifest, write_array, write_blob

ROOT = Path(__file__).resolve().parents[1]


def generate(out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    yy, xx = np.indices((29, 37))
    fixtures = {
        "black": np.zeros((29, 37), dtype=np.uint8),
        "midgray": np.full((29, 37), 128, dtype=np.uint8),
        "white": np.full((29, 37), 255, dtype=np.uint8),
        "ramp": np.tile(np.arange(256, dtype=np.uint8), (32, 1)),
        "step-horizontal": np.where(yy >= 14, 255, 0).astype(np.uint8),
        "step-vertical": np.where(xx >= 18, 255, 0).astype(np.uint8),
        "step-diagonal-down": np.where(xx * 28 >= yy * 36, 255, 0).astype(np.uint8),
        "step-diagonal-up": np.where(xx * 28 >= (28 - yy) * 36, 255, 0).astype(np.uint8),
        "impulse-center": np.zeros((29, 37), dtype=np.uint8),
        "impulse-corner": np.zeros((29, 37), dtype=np.uint8),
        "checker4": (((xx // 4 + yy // 4) % 2) * 255).astype(np.uint8),
        "noise": np.random.default_rng(20261104).integers(0, 256, (29, 37), dtype=np.uint8),
    }
    fixtures["impulse-center"][14, 18] = 255
    fixtures["impulse-corner"][0, 0] = 255
    colors = np.array([
        [255, 0, 0], [0, 255, 0], [0, 0, 255],
        [0, 255, 255], [255, 0, 255], [255, 255, 0],
    ], dtype=np.uint8).reshape(2, 3, 3)
    fixtures["rgb-patches"] = np.repeat(np.repeat(colors, 12, axis=0), 12, axis=1)
    # The dataset is copied into the repository so ordinary tests never fetch it.
    astronaut = data.astronaut()
    if astronaut.shape != (512, 512, 3) or astronaut.dtype != np.uint8:
        raise ValueError("skimage.data.astronaut(): unexpected source shape/dtype")
    fixtures["astronaut"] = astronaut
    fixtures["astronaut-portrait"] = astronaut[:, 128:384]
    fixtures["astronaut-landscape"] = astronaut[128:384, :]
    entries = []
    for fixture_id, pixels in fixtures.items():
        image = Image.fromarray(pixels)
        buffer = BytesIO()
        image.save(buffer, format="PNG", optimize=False, compress_level=9)
        entries.append({
            "id": fixture_id,
            **write_blob(out, f"{fixture_id}.png", buffer.getvalue()),
            "width": image.width, "height": image.height,
            "mode": image.mode,
        })
    attribution = (
        "Astronaut photographic fixture: Eileen Collins, NASA, public domain.\n"
        "Source: skimage.data.astronaut(), distributed by scikit-image.\n"
        "Dataset documentation: https://scikit-image.org/docs/0.25.x/api/skimage.data.html#skimage.data.astronaut\n"
        "scikit-image dataset record: https://github.com/scikit-image/scikit-image/blob/v0.25.2/skimage/data/_fetchers.py\n"
        "Original source: https://en.wikipedia.org/wiki/File:Eileen_Collins.jpg\n"
        "The portrait and landscape fixtures are unaltered pixel crops of this source.\n"
        "All synthetic fixtures were generated by qa/make_fixtures.py.\n"
    )
    tiny_inputs = [
        {"id": "tiny-1x1", "input": write_array(out, np.array([[128]], dtype=np.uint8))},
        {"id": "tiny-1x17", "input": write_array(out, np.arange(17, dtype=np.uint8).reshape(1, 17) * 15)},
        {"id": "tiny-17x1", "input": write_array(out, np.arange(17, dtype=np.uint8).reshape(17, 1) * 15)},
    ]
    manifest = {
        "schemaVersion": 1,
        "seed": 20261104,
        "fixtures": entries,
        "componentInputs": tiny_inputs,
        "attribution": write_blob(out, "ATTRIBUTION.txt", attribution.encode("utf-8")),
    }
    encoded = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
    write_blob(out, "manifest.json", encoded)
    return load_manifest(out / "manifest.json")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "qa/fixtures/images")
    args = parser.parse_args()
    manifest = generate(args.out.resolve())
    print(f"Verified {len(manifest['fixtures'])} canonical PNGs and {len(manifest['componentInputs'])} tiny component fixtures: {args.out / 'manifest.json'}")


if __name__ == "__main__":
    main()
